import fs from 'node:fs';
import assert from 'node:assert/strict';
import { previewAccountType, previewDisplayName } from '../src/utils/previewIdentity.js';
const client={role:'admin',rank:'Client',full_name:'jdoe',first_name:'Jane',last_name:'Doe'};
assert.equal(previewAccountType(client),'Client');
