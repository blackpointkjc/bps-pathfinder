import assert from 'node:assert/strict';
import {isOutOfOffice} from '../src/utils/outOfOffice.js';
import {actingCoverage,platoonCommander,primarySiteReportingChain} from '../src/utils/commandReporting.js';
const now=Date.now();
const away={out_of_office:true,out_of_office_start:new Date(now-10000).toISOString(),out_of_office_return:new Date(now+600000).toISOString()};
assert.equal(isOutOfOffice(away,now),true);
assert.equal(isOutOfOffice(away,Date.parse(away.out_of_office_return)),false);
assert.equal(isOutOfOffice(away,now-20000),false);
assert.equal(isOutOfOffice({...away,out_of_office:false},now),false);
const colonel={id:'col',rank:'Colonel'};
const major={id:'m',rank:'Major',oversight_platoon:'A',supervisor_id:'col'};
const cpt={id:'c',rank:'Captain',platoon:'A',supervisor_id:'m',email:'c@test',...away};
const lt={id:'l',rank:'Lieutenant',platoon:'A',supervisor_id:'c',email:'l@test'};
const sgt={id:'s',rank:'Sergeant',platoon:'A',supervisor_id:'l'};
const users=[colonel,major,cpt,lt,sgt];
assert.equal(platoonCommander('A',users).id,'l');
assert.equal(actingCoverage(cpt,users).id,'l');
assert.equal(actingCoverage({...sgt,...away},users).id,'l');
assert.equal(platoonCommander('A',[colonel,major,cpt]).id,'m');
const chain=primarySiteReportingChain(['c@test'],users);
assert.equal(chain.levels[0][0].id,'l');
assert.equal(chain.actingFor.id,'c');
assert.equal(chain.levels.some(level=>level.some(person=>person.id==='c')),false);
assert.equal(primarySiteReportingChain(['c@test'],users.map(user=>user.id==='c'?{...user,out_of_office:false}:user)).levels[0][0].id,'c');
assert.equal(cpt.supervisor_id,'m');
console.log('PASS: scheduled start, exact return, early return, lower/higher coverage, acting site chain, permanent assignment preservation');
